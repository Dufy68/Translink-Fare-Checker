source("R/core.R")
checks <- 0L
check <- function(x) { stopifnot(isTRUE(x)); checks <<- checks + 1L }
f <- function(fare=.5, date="2026-09-01", credit=0, to="South Bank") data.frame(Date=date, Time="08:00", From="Central", To=to, Fare=fare, Credit=credit, Balance=20)
a <- function(x, scope=TRUE) analyze_fares(prepare_data(x), scope, as.Date("2026-10-31"))
check(identical(parse_money(c("-$2.50", "($5.00)", "$1,234.50", "", "oops")), c(-2.5,-5,1234.5,NA_real_,NA_real_)))
check(a(f(3.2))$Potential_Difference == 2.7)
check(a(f(2.5))$Potential_Difference == 2)
check(a(f(.5))$Status == "Within baseline")
check(a(f(0))$Status == "Review context")
check(a(f(0, credit=20))$Type == "Top-up / credit")
check(is.na(a(f(0, credit=20))$Potential_Difference))
check(a(f(-2))$Type == "Adjustment")
check(a(f(NA))$Type == "Unresolved")
check(a(f(1, credit=5))$Type == "Mixed transaction")
check(a(f(3.2,"2024-08-04"))$Rule == "UNASSESSED")
check(a(f(3.2,"2024-08-05"))$Potential_Difference == 2.7)
check(a(f(3.2,"2030-01-01"))$Rule == "UNASSESSED")
check(a(f(3.2,"bad"))$Rule == "UNASSESSED")
check(a(f(3.2),FALSE)$Rule == "UNASSESSED")
check(a(f(25,to="Domestic Airport"))$Rule == "UNASSESSED")
check(a(f(.5,to=""))$Rule == "UNASSESSED")
check(a(f(0,to="Failed to tap off"))$Status == "Review suggested")
d <- a(rbind(f(),f())); check(all(d$Duplicate)); check(nrow(metric_rows(d)) == 0)
check(commute_budget(5,2,.5) == 21.67)
check(commute_budget(0,2,.5) == 0)
check(inherits(try(prepare_data(data.frame(X=1)),silent=TRUE),"try-error"))
check(inherits(try(commute_budget(-1,2,.5),silent=TRUE),"try-error"))
check(as.character(parse_dates("05/08/2024")) == "2024-08-05")
cat(sprintf("Passed %s regression checks.\n",checks))
c <- carbon_scenario(5, 2, 10, 10, 100, 200, 1, 20)
check(abs(c$pt - 43.333333) < 1e-5)
check(abs(c$car - 86.666667) < 1e-5)
check(c$lower <= c$difference && c$upper >= c$difference)
c2 <- carbon_scenario(5, 2, 10, 10, 100, 200, 2, 0)
check(c2$pt == c$pt && c2$car == c$car/2)
check(c2$difference == 0 && c2$lower == 0 && c2$upper == 0)
check(carbon_scenario(0, 2, 10, 10, 100, 200)$pt == 0)
check(carbon_scenario(5, 2, 10, 10, 300, 100)$difference < 0)
for (bad in list(NA_real_, Inf, -1, numeric(0), c(1,2))) check(inherits(try(carbon_scenario(bad,2,10,10,100,200),silent=TRUE),"try-error"))
check(inherits(try(carbon_scenario(5,2,10,10,100,200,0),silent=TRUE),"try-error"))
check(inherits(try(carbon_scenario(5,2,10,10,100,200,1,101),silent=TRUE),"try-error"))
cat(sprintf("Passed %s total checks, including carbon scenarios.\n",checks))
